export const themes = themesData
export const DEFAULT_THEME_ID = 'rose-quartz'

export function hexToRgbString(hex) {
  const clean = hex.replace('#', '')
  if (clean.length !== 6) return '225 29 72'
  const r = parseInt(clean.slice(0, 2), 16)
  const g = parseInt(clean.slice(2, 4), 16)
  const b = parseInt(clean.slice(4, 6), 16)
  return `${r} ${g} ${b}`
}

export function applyTheme(themeOrId) {
  const theme =
    typeof themeOrId === 'string'
      ? themesData.find((t) => t.id === themeOrId) || themesData[0]
      : themeOrId || themesData[0]

  const root = document.documentElement
  Object.entries(theme.colors).forEach(([key, hex]) => {
    root.style.setProperty(`--${key}`, hexToRgbString(hex))
  })
  root.dataset.theme = theme.id
  root.style.colorScheme = theme.mode
  return theme
}

export function themeToCssVariables(theme) {
  const c = theme.colors
  return `/* ${theme.name} (${theme.mode}) — CSS Custom Properties */
:root {
  --bg: ${hexToRgbString(c.bg)};
  --surface: ${hexToRgbString(c.surface)};
  --fg: ${hexToRgbString(c.fg)};
  --muted: ${hexToRgbString(c.muted)};
  --line: ${hexToRgbString(c.line)};
  --primary: ${hexToRgbString(c.primary)};
  --accent: ${hexToRgbString(c.accent)};
}`
}